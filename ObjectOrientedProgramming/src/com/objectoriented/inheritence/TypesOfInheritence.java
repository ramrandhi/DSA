package com.objectoriented.inheritence;

public class TypesOfInheritence {
	/*
	 	1. single level inheritance
	 	
	 	-> a child class extends a parent class it is called single level inheritance
	 	
	 	2. multi-level inheritance
	 	
	 	-> a parent class extended by child class and that child class is extended by another child class is called multi-level 
	 		inheritance
	 	
	 	3. multiple inheritance
	 	
	 	-> a child classes two  or more parent classes and they are extending by single child class
	 	-> it is not supported by java due to ambiguity where two parent classes having two variables or functions same that creates
	 		ambiguity to child class to which one to pick but we can achieve this using interfaces.
	 		
	 	4. hirarchiel inheritance
	 	
	 	-> one class is inherited by many child classes
	 	
	 	5. hybrid inheritance
	 	
	 	-> one parent class is inherited by multiple child classes and that multiple classes are inherited by one child class again
	 	-> Here also there is a chance of ambiguity as in second step multiple classes is extended by a single class here this class
	 		may undergo while accessing properties of multiple parent classes.
	 	-> but we can achieve this by using interfaces.
	 */

}
